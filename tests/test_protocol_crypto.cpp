TEST(ProtocolCryptoTest, ChaCha20Poly1305MatchesRfc8439AndRejectsTampering) {
    constexpr ProtocolCrypto::ChaCha20Poly1305Key key{
        0x80, 0x81, 0x82, 0x83, 0x84, 0x85, 0x86, 0x87, 0x88, 0x89, 0x8A,
        0x8B, 0x8C, 0x8D, 0x8E, 0x8F, 0x90, 0x91, 0x92, 0x93, 0x94, 0x95,
        0x96, 0x97, 0x98, 0x99, 0x9A, 0x9B, 0x9C, 0x9D, 0x9E, 0x9F,
    };
    constexpr ProtocolCrypto::ChaCha20Poly1305Nonce nonce{
        0x07, 0x00, 0x00, 0x00, 0x40, 0x41, 0x42, 0x43, 0x44, 0x45, 0x46, 0x47,
    };
    constexpr std::array<uint8_t, 12> aad{
        0x50, 0x51, 0x52, 0x53, 0xC0, 0xC1, 0xC2, 0xC3, 0xC4, 0xC5, 0xC6, 0xC7,
    };
    constexpr char plaintext[] =
        "Ladies and Gentlemen of the class of '99: If I could offer you only one tip for the future, sunscreen would be it.";
    constexpr std::array<uint8_t, 114> expected_ciphertext{
        0xD3, 0x1A, 0x8D, 0x34, 0x64, 0x8E, 0x60, 0xDB, 0x7B, 0x86, 0xAF, 0xBC,
        0x53, 0xEF, 0x7E, 0xC2, 0xA4, 0xAD, 0xED, 0x51, 0x29, 0x6E, 0x08, 0xFE,
        0xA9, 0xE2, 0xB5, 0xA7, 0x36, 0xEE, 0x62, 0xD6, 0x3D, 0xBE, 0xA4, 0x5E,
        0x8C, 0xA9, 0x67, 0x12, 0x82, 0xFA, 0xFB, 0x69, 0xDA, 0x92, 0x72, 0x8B,
        0x1A, 0x71, 0xDE, 0x0A, 0x9E, 0x06, 0x0B, 0x29, 0x05, 0xD6, 0xA5, 0xB6,
        0x7E, 0xCD, 0x3B, 0x36, 0x92, 0xDD, 0xBD, 0x7F, 0x2D, 0x77, 0x8B, 0x8C,
        0x98, 0x03, 0xAE, 0xE3, 0x28, 0x09, 0x1B, 0x58, 0xFA, 0xB3, 0x24, 0xE4,
        0xFA, 0xD6, 0x75, 0x94, 0x55, 0x85, 0x80, 0x8B, 0x48, 0x31, 0xD7, 0xBC,
        0x3F, 0xF4, 0xDE, 0xF0, 0x8E, 0x4B, 0x7A, 0x9D, 0xE5, 0x76, 0xD2, 0x65,
        0x86, 0xCE, 0xC6, 0x4B, 0x61, 0x16,
    };
    constexpr ProtocolCrypto::ChaCha20Poly1305Tag expected_tag{
        0x1A, 0xE1, 0x0B, 0x59, 0x4F, 0x09, 0xE2, 0x6A, 0x7E, 0x90, 0x2E,
        0xCB, 0xD0, 0x60, 0x06, 0x91,
    };
    std::array<uint8_t, expected_ciphertext.size()> ciphertext{};
    std::array<uint8_t, expected_ciphertext.size()> decrypted{};
    const std::array<uint8_t, expected_ciphertext.size()> zero_plaintext{};
    ProtocolCrypto::ChaCha20Poly1305Tag tag{};

    ASSERT_TRUE(ProtocolCrypto::chacha20_poly1305_encrypt(key, nonce, aad.data(), aad.size(),
                                                            reinterpret_cast<const uint8_t*>(plaintext),
                                                            sizeof(plaintext) - 1,
                                                            ciphertext.data(), &tag));
    EXPECT_EQ(ciphertext, expected_ciphertext);
    EXPECT_EQ(tag, expected_tag);
    ASSERT_TRUE(ProtocolCrypto::chacha20_poly1305_decrypt(key, nonce, aad.data(), aad.size(),
                                                            ciphertext.data(), ciphertext.size(), tag,
                                                            decrypted.data()));
    EXPECT_EQ(std::memcmp(decrypted.data(), plaintext, decrypted.size()), 0);

    tag[0] ^= 1U;
    decrypted.fill(0xFF);
    EXPECT_FALSE(ProtocolCrypto::chacha20_poly1305_decrypt(key, nonce, aad.data(), aad.size(),
                                                             ciphertext.data(), ciphertext.size(), tag,
                                                             decrypted.data()));
    EXPECT_EQ(decrypted, zero_plaintext);

    ProtocolCrypto::ChaCha20Poly1305Tag empty_tag{};
    ASSERT_TRUE(ProtocolCrypto::chacha20_poly1305_encrypt(key, nonce, nullptr, 0, nullptr, 0, nullptr,
                                                            &empty_tag));
    EXPECT_TRUE(ProtocolCrypto::chacha20_poly1305_decrypt(key, nonce, nullptr, 0, nullptr, 0, empty_tag,
                                                            nullptr));
}

